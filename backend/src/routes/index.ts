import { Router } from 'express';
import { adminRouter } from './admin/index.js';
import { authRouter } from './auth.routes.js';
import { customerRouter } from './customer/index.js';
import { customerListRouter } from './customer-list.routes.js';
import { bannerRouter, uploadRouter } from './banner.routes.js';
import { promoRouter } from './promo.routes.js';
import { resourceCategoryRouter } from './resource-category.routes.js';
import { adminCleanerTaskRoutes, cleanerTaskRouter } from './cleaner-task.routes.js';
import { authenticate } from '../middleware/auth.middleware.js';
import { requireAdmin } from '../middleware/admin.middleware.js';
import { faqRouter } from './faq.routes.js';
import { staffRouter } from './staff.routes.js';
import { platformServiceRouter } from './service.routes.js';
import { orderRouter } from './order.routes.js';
import { scheduleRouter } from './schedule.routes.js';
import { trackingRouter } from './tracking.routes.js';

export const apiRouter = Router();
apiRouter.use('/auth', authRouter);
apiRouter.use('/customer', customerRouter);
apiRouter.use('/customers', authenticate, requireAdmin, customerListRouter);
apiRouter.use('/admin', adminRouter);
apiRouter.use('/orders', authenticate, requireAdmin, orderRouter);
apiRouter.use('/services', authenticate, requireAdmin, platformServiceRouter);
apiRouter.use('/faqs', authenticate, requireAdmin, faqRouter);
apiRouter.use('/staff', authenticate, requireAdmin, staffRouter);
apiRouter.use('/schedules', authenticate, requireAdmin, scheduleRouter);
apiRouter.use('/categories', resourceCategoryRouter);
apiRouter.use('/promos', promoRouter);
apiRouter.use('/banners', bannerRouter);
apiRouter.use('/uploads', uploadRouter);
adminCleanerTaskRoutes(apiRouter);
apiRouter.use('/cleaner-task', cleanerTaskRouter);
apiRouter.use('/tracking', trackingRouter);
